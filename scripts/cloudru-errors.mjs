/** Достаёт текст ошибки из тела ответа сервиса (OpenAI-формат и близкие). */
export function apiMessage(text) {
  if (!text) return "";
  try {
    const j = JSON.parse(text), e = j?.error ?? j;
    const m = typeof e === "string" ? e : e?.message ?? e?.detail ?? j?.message ?? j?.detail;
    return typeof m === "string" ? m.replace(/\s+/g, " ").trim().slice(0, 240) : "";
  } catch { return text.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim().slice(0, 160); }
}

/** Ошибка HTTP → { error, hint, code }. */
export function explainHttp(status, apiMsg = "") {
  const g = HTTP_GUIDE.find((x) => x.code === status);
  const title = g ? `${g.title} (${status})` : `Сервис ответил HTTP ${status}`;
  const hint = g?.hint ?? (status >= 500 ? "Сбой на стороне Cloud.ru. Повторите позже." : "Проверьте ключ, модель и адрес API в «Настройках».");
  return { error: title, hint, code: status, detail: apiMsg || undefined };
}

/** Сетевая ошибка fetch → { error, hint, code }. */
export function explainNet(e) {
  const c = String(e?.cause?.code ?? e?.cause?.errors?.[0]?.code ?? e?.code ?? "");
  const key = /CERT|SELF_SIGNED|TLS/.test(c) ? "CERT" : c;
  if (e?.name === "TimeoutError" || key === "TIMEOUT") { const g = NET_GUIDE.find((x) => x.code === "TIMEOUT"); return { error: g.title, hint: g.hint, code: "TIMEOUT" }; }
  const g = NET_GUIDE.find((x) => x.code === key);
  if (g) return { error: g.title + ` (${c})`, hint: g.hint, code: c };
  return { error: "Нет связи с сервисом" + (c ? ` (${c})` : ""), hint: "Проверьте интернет и адрес API в «Настройках» → «Подключение».", code: c || "NET" };
}

